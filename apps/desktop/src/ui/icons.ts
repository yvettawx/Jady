/** Names every scheme is expected to cover; plugins may register more. */
export type IconName = keyof typeof LUCIDE;

export interface IconScheme {
  id: string;
  /** Icons this scheme replaces; anything missing falls back to the default scheme. */
  icons: Partial<Record<string, IconComponent>>;
}

export const DEFAULT_ICON_SCHEME = "lucide";
const defaults: IconScheme = { id: DEFAULT_ICON_SCHEME, icons: { ...LUCIDE } };
const schemes = new Map<string, IconScheme>([[DEFAULT_ICON_SCHEME, defaults]]);
let active = DEFAULT_ICON_SCHEME;

export function registerIconScheme(scheme: IconScheme): void {
  schemes.set(scheme.id, scheme);
}

/** Adds icons under new names to the default scheme, e.g. for a plugin's own panel. */
export function registerIcons(icons: Record<string, IconComponent>): void {
  Object.assign(defaults.icons, icons);
}

export function setIconScheme(id: string): void {
  if (!schemes.has(id)) throw new Error(`unknown icon scheme: ${id}`);
  active = id;
}

export function resolveIcon(name: string): IconComponent | undefined {
  return schemes.get(active)?.icons[name] ?? defaults.icons[name];
}
